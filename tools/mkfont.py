#!/usr/bin/env python3
"""Converts a monospace BDF font into a Traboda font module (1 bpp, MONO_HLSB rows).

Usage: tools/mkfont.py FONT.bdf OUT.py [--chars digits|text] [--source "credit line"]

The module holds W, H, CHARS (the characters it covers, in glyph order) and DATA (bytes,
H rows of ceil(W/8) bytes per glyph). traboda.gfx draws it with framebuf.blit and a
two-colour palette, so text rendering runs in C.
"""

import argparse

TEXT = (
    "".join(chr(c) for c in range(32, 127))
    + "àáèéìíòóùúÀÁÈÉÌÍÒÓÙÚçÇñÑäëïöüÄËÏÖÜß°€£¥©®±×÷µ¿¡«»…•·"
    + "←↑→↓↔▲▼◀▶►◄■□▪●○◆★☆♪♫♥✓✗⏻‖"
    + "░▒▓█▀▄▌▐─│┌┐└┘├┤┬┴┼═║"
)
DIGITS = "0123456789:.-+%° APMapm"


def parse_bdf(path):
    glyphs, props = {}, {}
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        key, _, rest = line.partition(" ")
        if key == "FONTBOUNDINGBOX":
            props["box"] = [int(v) for v in rest.split()]
        elif key in ("FONT_ASCENT", "FONT_DESCENT"):
            props[key] = int(rest)
        elif key == "STARTCHAR":
            enc, bbx, rows = None, None, []
            for line in lines:
                key, _, rest = line.partition(" ")
                if key == "ENCODING":
                    enc = int(rest.split()[0])
                elif key == "BBX":
                    bbx = [int(v) for v in rest.split()]
                elif key == "BITMAP":
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(int(line, 16) if line else 0)
                    break
            if enc is not None and enc >= 0:
                glyphs[enc] = (bbx, rows)
    return props, glyphs


def render(props, glyph, w, h):
    """Glyph placed in a w x h cell as h rows of ceil(w/8) bytes, MSB first."""
    (gw, gh, gx, gy), rows = glyph
    ascent = props.get("FONT_ASCENT", h)
    nbytes = (w + 7) // 8
    out = bytearray(nbytes * h)
    rbits = ((gw + 7) // 8) * 8
    top = ascent - (gy + gh)
    for r, bits in enumerate(rows):
        y = top + r
        if not 0 <= y < h:
            continue
        for c in range(gw):
            if bits >> (rbits - 1 - c) & 1:
                x = gx + c
                if 0 <= x < w:
                    out[y * nbytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(out)


def synth(ch, w, h):
    """Glyphs Spleen lacks, drawn geometrically: play/back triangles, check, cross."""
    nbytes = (w + 7) // 8
    out = bytearray(nbytes * h)

    def dot(x, y):
        if 0 <= x < w and 0 <= y < h:
            out[y * nbytes + x // 8] |= 0x80 >> (x % 8)

    if ch in "▶►◀◄":
        size = min(w - 1, h // 2)
        top = (h - 2 * size) // 2
        x0 = (w - size) // 2
        for i in range(2 * size + 1):
            span = size - abs(size - i)
            for j in range(span):
                dot(x0 + j if ch in "▶►" else x0 + size - 1 - j, top + i)
    elif ch == "✓":
        for i in range(w):
            y = h // 2 + i if i < w // 3 else h // 2 + w // 3 - (i - w // 3)
            dot(i, y)
            dot(i, y + 1)
    elif ch == "✗":
        m = min(w, h) - 2
        y0 = (h - m) // 2
        for i in range(m):
            dot(i + (w - m) // 2, y0 + i)
            dot(w - 1 - i - (w - m) // 2, y0 + i)
    else:
        return None
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bdf")
    ap.add_argument("out")
    ap.add_argument("--chars", default="text", choices=("text", "digits"))
    ap.add_argument("--source", default="")
    args = ap.parse_args()

    props, glyphs = parse_bdf(args.bdf)
    w, h = props["box"][0], props["box"][1]
    wanted = TEXT if args.chars == "text" else DIGITS
    chars, data, missing = [], bytearray(), []
    for ch in wanted:
        if ord(ch) in glyphs:
            chars.append(ch)
            data += render(props, glyphs[ord(ch)], w, h)
        elif synth(ch, w, h) is not None:
            chars.append(ch)
            data += synth(ch, w, h)
        else:
            missing.append(ch)

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# Generated by tools/mkfont.py from %s. Do not edit.\n" % args.bdf.split("/")[-1])
        if args.source:
            f.write("# %s\n" % args.source)
        f.write("W = %d\nH = %d\n" % (w, h))
        f.write("CHARS = %r\n" % "".join(chars))
        f.write("DATA = %r\n" % bytes(data))
    print("%s: %dx%d, %d glyphs, %d bytes%s" % (
        args.out, w, h, len(chars), len(data),
        ", missing: " + "".join(missing) if missing else ""))


if __name__ == "__main__":
    main()
