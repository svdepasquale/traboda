"""Drawing on the display's framebuffer: text, icons and shapes.

Text and icons go through framebuf.blit with a palette, so the per-pixel work runs in C;
Python only walks the characters. Colours are byte-swapped RGB565 from display.rgb().
"""

import framebuf

from .display import H, W, rgb

fb = None       # the display's FrameBuffer, set by attach()
_pal2 = framebuf.FrameBuffer(bytearray(4), 2, 1, framebuf.RGB565)
_KEY = 0x0120   # a colour no theme uses: the transparent key for palette blits


def attach(framebuffer):
    global fb
    fb = framebuffer


class Font:
    """A monospace 1 bpp font generated by tools/mkfont.py."""

    def __init__(self, mod):
        self.w = mod.W
        self.h = mod.H
        self.chars = mod.CHARS
        self._data = bytearray(mod.DATA)  # framebuf needs a writable buffer
        self._mv = memoryview(self._data)
        self._stride = (self.w + 7) // 8 * self.h
        self._cache = {}
        self._fallback = max(0, self.chars.find("?"))

    def glyph(self, ch):
        g = self._cache.get(ch)
        if g is None:
            i = self.chars.find(ch)
            if i < 0:
                i = self._fallback
            off = i * self._stride
            g = framebuf.FrameBuffer(self._mv[off:off + self._stride], self.w, self.h, framebuf.MONO_HLSB)
            self._cache[ch] = g
        return g

    def width(self, s):
        return len(s) * self.w


_fonts = {}


def font(name):
    """small 6x12, text 8x16, title 12x24, large 16x32, huge 32x64 (digits only)."""
    f = _fonts.get(name)
    if f is None:
        mod = __import__("traboda.fonts." + name, None, None, ("W",))
        f = _fonts[name] = Font(mod)
    return f


def text(s, x, y, color, f="text", bg=None, align=0):
    """Draws s at (x, y); align -1 right-aligns on x, 0 left, 1 centres on x. Returns width."""
    if isinstance(f, str):
        f = font(f)
    width = len(s) * f.w
    if align == 1:
        x -= width // 2
    elif align == -1:
        x -= width
    if bg is None:
        _pal2.pixel(0, 0, _KEY)
        key = _KEY
    else:
        _pal2.pixel(0, 0, bg)
        key = -1
    _pal2.pixel(1, 0, color)
    blit = fb.blit
    glyph = f.glyph
    step = f.w
    for ch in s:
        blit(glyph(ch), x, y, key, _pal2)
        x += step
    return width


def text_scaled(s, x, y, color, f="text", scale=2, align=0):
    """Pixel-doubled text for one-off big labels (slow: per pixel in Python)."""
    if isinstance(f, str):
        f = font(f)
    width = len(s) * f.w * scale
    if align == 1:
        x -= width // 2
    elif align == -1:
        x -= width
    fill_rect = fb.fill_rect
    for ch in s:
        g = f.glyph(ch)
        for gy in range(f.h):
            for gx in range(f.w):
                if g.pixel(gx, gy):
                    fill_rect(x + gx * scale, y + gy * scale, scale, scale, color)
        x += f.w * scale
    return width


def wrap(s, width, f="text"):
    """Splits s into lines that fit width pixels, breaking on spaces where possible."""
    if isinstance(f, str):
        f = font(f)
    per_line = max(1, width // f.w)
    lines = []
    for para in s.split("\n"):
        line = ""
        for word in para.split(" "):
            while len(word) > per_line:
                if line:
                    lines.append(line)
                    line = ""
                lines.append(word[:per_line])
                word = word[per_line:]
            if not line:
                line = word
            elif len(line) + 1 + len(word) <= per_line:
                line += " " + word
            else:
                lines.append(line)
                line = word
        lines.append(line)
    return lines


def ellipsize(s, width, f="text"):
    if isinstance(f, str):
        f = font(f)
    n = width // f.w
    if len(s) <= n:
        return s
    if "…" in f.chars:
        return s[:max(0, n - 1)] + "…"
    return s[:max(0, n - 2)] + ".."


# Shapes -------------------------------------------------------------------------------

def clear(color=0):
    fb.fill(color)


def fill_rect(x, y, w, h, c):
    fb.fill_rect(x, y, w, h, c)


def rect(x, y, w, h, c):
    fb.rect(x, y, w, h, c)


def hline(x, y, w, c):
    fb.hline(x, y, w, c)


def vline(x, y, h, c):
    fb.vline(x, y, h, c)


def line(x0, y0, x1, y1, c):
    fb.line(x0, y0, x1, y1, c)


def circle(x, y, r, c, fill=False):
    fb.ellipse(x, y, r, r, c, fill)


def round_rect(x, y, w, h, r, c, fill=True):
    """Rectangle with radius-r corners (r small: 2..8)."""
    if r <= 0:
        (fb.fill_rect if fill else fb.rect)(x, y, w, h, c)
        return
    if fill:
        fb.fill_rect(x + r, y, w - 2 * r, h, c)
        fb.fill_rect(x, y + r, r, h - 2 * r, c)
        fb.fill_rect(x + w - r, y + r, r, h - 2 * r, c)
        # quadrant masks: 1 top-right, 2 top-left, 4 bottom-left, 8 bottom-right
        fb.ellipse(x + r, y + r, r, r, c, True, 2)
        fb.ellipse(x + w - r - 1, y + r, r, r, c, True, 1)
        fb.ellipse(x + r, y + h - r - 1, r, r, c, True, 4)
        fb.ellipse(x + w - r - 1, y + h - r - 1, r, r, c, True, 8)
    else:
        fb.hline(x + r, y, w - 2 * r, c)
        fb.hline(x + r, y + h - 1, w - 2 * r, c)
        fb.vline(x, y + r, h - 2 * r, c)
        fb.vline(x + w - 1, y + r, h - 2 * r, c)
        fb.ellipse(x + r, y + r, r, r, c, False, 2)
        fb.ellipse(x + w - r - 1, y + r, r, r, c, False, 1)
        fb.ellipse(x + r, y + h - r - 1, r, r, c, False, 4)
        fb.ellipse(x + w - r - 1, y + h - r - 1, r, r, c, False, 8)


def gradient_v(x, y, w, h, top, bottom):
    """Vertical gradient between two (r, g, b) tuples."""
    r0, g0, b0 = top
    r1, g1, b1 = bottom
    span = max(1, h - 1)
    for i in range(h):
        fb.hline(x, y + i, w,
                 rgb(r0 + (r1 - r0) * i // span, g0 + (g1 - g0) * i // span, b0 + (b1 - b0) * i // span))


def bar(x, y, w, h, fraction, fg, bg, r=0):
    """Horizontal progress bar."""
    fraction = 0 if fraction < 0 else 1 if fraction > 1 else fraction
    round_rect(x, y, w, h, r, bg)
    fw = int(w * fraction)
    if fw > 0:
        round_rect(x, y, max(fw, 2 * r), h, r, fg)


def blit(src, x, y, key=-1, palette=None):
    fb.blit(src, x, y, key, palette)


