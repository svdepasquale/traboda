_cache = {}


def _parse(name, scale):
    rows = ART[name]
    size = 16 * scale
    buf = bytearray(size * size // 2)
    icon = framebuf.FrameBuffer(buf, size, size, framebuf.GS4_HMSB)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row[:16]):
            slot = _SLOTS.find(ch)
            if slot > 0:
                if scale == 1:
                    icon.pixel(x, y, slot)
                else:
                    icon.fill_rect(x * scale, y * scale, scale, scale, slot)
    return icon


def get(name, scale=2):
    key = (name, scale)
    icon = _cache.get(key)
    if icon is None:
        icon = _cache[key] = _parse(name if name in ART else "info", scale)
    return icon


def draw(fb, name, x, y, scale=2):
    fb.blit(get(name, scale), x, y, _KEY, palette)
